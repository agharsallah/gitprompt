//! The dashboard's API types, generated from the Rust wire types (`web/src/lib/api/generated.ts`).
//!
//! This test renders every type the HTTP API answers or accepts, with everything they reference,
//! into one TypeScript file, and fails when the committed file differs: a field renamed or retyped
//! in Rust then fails `cargo test` (and CI) instead of breaking the dashboard at runtime.
//!
//! Regenerate after changing a wire type: `just types` (runs this test with `UPDATE_TS_TYPES=1`).
#![allow(clippy::panic, clippy::expect_used, unreachable_pub, reason = "integration test: a panic is a test failure")]

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::path::PathBuf;

use ts_rs::{Config, TS, TypeVisitor};

use gitprompt_server::model;

const HEADER: &str = "// GENERATED by `just types` from the Rust wire types (backend/crates/gitprompt-server/tests/ts_types.rs).\n\
// Do not edit: change the Rust type, then run `just types`. `cargo test` fails while this file is stale.\n";

/// Collects the declaration of each type it visits and of everything that type references.
struct Collect<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    decls: BTreeMap<String, String>,
}

impl TypeVisitor for Collect<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return; // a built-in (string, number, arrays, maps…) or already declared
        }
        let docs = T::docs().map(|d| format!("{d}\n")).unwrap_or_default();
        let name = T::ident(self.cfg);
        let decl = format!("{docs}export {}\n", T::decl(self.cfg));
        if let Some(previous) = self.decls.insert(name.clone(), decl.clone()) {
            assert_eq!(previous, decl, "two Rust types are both named `{name}` in TypeScript: rename one with #[ts(rename)]");
        }
        T::visit_dependencies(self);
    }
}

/// The types the dashboard reads or sends (roots; their dependencies follow).
fn roots(c: &mut Collect<'_>) {
    // prompts
    c.visit::<model::PromptOut>();
    c.visit::<model::PromptDetail>();
    c.visit::<model::Annotation>();
    c.visit::<model::Updated>();
    // stats, stories, search, fields
    c.visit::<model::Stats>();
    c.visit::<gitprompt_store::stats::Order>();
    c.visit::<model::Telemetry>();
    c.visit::<model::SessionStory>();
    c.visit::<model::ProjectStory>();
    c.visit::<model::Lineage>();
    c.visit::<model::SearchResults>();
    c.visit::<model::Catalog>();
    // connectors
    c.visit::<model::SourceOut>();
    c.visit::<model::RecentCapture>();
    c.visit::<model::SpecText>();
    c.visit::<model::Change>();
    c.visit::<model::Enabled>();
    // settings, data, security, export
    c.visit::<gitprompt_core::preferences::Preferences>();
    c.visit::<model::SettingsOut>();
    c.visit::<model::SettingsSaved>();
    c.visit::<model::DataOut>();
    c.visit::<model::CompactIn>();
    c.visit::<model::DeleteIn>();
    c.visit::<model::ReportOut>();
    c.visit::<model::SecurityOut>();
    c.visit::<model::Rotation>();
    c.visit::<model::ChartInfo>();
}

fn render() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut collect = Collect { cfg: &cfg, seen: HashSet::new(), decls: BTreeMap::new() };
    roots(&mut collect);
    let body: Vec<String> = collect.decls.into_values().collect();
    format!("{HEADER}\n{}", body.join("\n"))
}

fn generated_file() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../web/src/lib/api/generated.ts")
}

#[test]
fn the_dashboard_types_match_the_rust_wire_types() {
    let path = generated_file();
    let expected = render();
    if std::env::var_os("UPDATE_TS_TYPES").is_some() {
        std::fs::write(&path, &expected).expect("write generated.ts");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(committed == expected, "{} is out of date with the Rust wire types: run `just types` and commit the result", path.display());
}
